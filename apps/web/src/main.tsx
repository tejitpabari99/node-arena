import { contentFiles } from './app/boot';
import { createAppController } from './app/state';
import { createBrowserRuntime } from './app/runtime';
import { createInputController } from './input';
import { mountApp } from './ui/App';
import './style.css';
const root=document.getElementById('app');if(!root)throw Error('Missing app root');
const arena=document.createElement('div');arena.id='arena';arena.setAttribute('aria-label','Arena');document.body.prepend(arena);
const app=createAppController({files:contentFiles(),createRuntime:context=>createBrowserRuntime(context,arena,(ctx,stage)=>createInputController({canvas:stage.canvas,sim:ctx.driver.sim,camera:stage.camera,world:stage.world,worldRoot:stage.worldRoot,scene:stage.scene,driver:ctx.driver,isEnabled:()=>ctx.enabled()&&!ctx.driver.paused}))});
const unsubscribe=app.subscribe(()=>{const state=app.snapshot();arena.hidden=state.screen!=='playing'&&state.screen!=='result'&&!app.driver;});
const unmount=mountApp(app,root);void app.boot();
if(import.meta.hot)import.meta.hot.dispose(()=>{unsubscribe();unmount();app.dispose();arena.remove();});
